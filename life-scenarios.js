    var scenarios = createScenarios(root);
    var added = 0;
    scenarios.forEach(function(e){
      if (!current[e.id]) { LS.events.push(e); current[e.id]=true; added++; }
    });
    LS._lifeScenariosInstalled = true;
    LS._lifeScenarioCount = added;
    LS.LifeScenarios = { createScenarios:createScenarios, count:added, version:'2026-10-30.1' };
